/** A city photo: the cover, or — with a seed such as a flight id — one of the city's other photos. */
export function cityPhoto(city, seed) {
  const ids = CITY_GALLERY[city];
  if (!ids) return TYPE_PHOTOS.activity;
  return U(seed == null ? ids[0] : ids[Math.abs(Number(seed) || 0) % ids.length]);
}

/** Resize an Unsplash URL on the fly (other URLs, e.g. uploads, are returned unchanged). */
export const sized = (url, w) => (url && url.includes("images.unsplash.com") ? url.replace(/([?&])w=\d+/, `$1w=${w}`) : url);
